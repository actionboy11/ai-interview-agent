  prompt_tokens integer,
  completion_tokens integer,
  total_tokens integer,
  artifact_key varchar(500),
  error_type varchar(160),
  error_summary varchar(500),
  observed_at timestamp(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ai_call_audit_stage ON ai_call_audits (stage_id);
CREATE INDEX idx_ai_call_audit_observed ON ai_call_audits (observed_at);

-- Spring AI PgVectorStore 2.0 defaults: UUID IDs and JSON metadata.
CREATE TABLE vector_store (
  id uuid DEFAULT public.uuid_generate_v4() PRIMARY KEY,
  content text,
  metadata json,
  embedding public.vector(1024)
);
CREATE INDEX spring_ai_vector_index ON vector_store USING hnsw (embedding public.vector_cosine_ops);
