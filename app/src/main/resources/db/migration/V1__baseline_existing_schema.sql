-- These pre-existing tables are included without extending agent-evaluation functionality.
CREATE TABLE agent_evaluation_runs (
  id varchar(36) PRIMARY KEY,
  name varchar(120) NOT NULL,
  dataset_version varchar(80) NOT NULL,
  prompt_version varchar(80) NOT NULL,
  git_commit varchar(64) NOT NULL,
  provider varchar(64) NOT NULL,
  model varchar(120) NOT NULL,
  planned_cases integer NOT NULL,
  completed_cases integer NOT NULL,
  status varchar(20) NOT NULL
    CHECK (status IN ('CREATED', 'RUNNING', 'PAUSED', 'COMPLETED', 'FAILED', 'CANCELLED')),
  pause_reason varchar(500),
  created_at timestamp(6) WITH TIME ZONE NOT NULL,
  started_at timestamp(6) WITH TIME ZONE,
  updated_at timestamp(6) WITH TIME ZONE NOT NULL,
  completed_at timestamp(6) WITH TIME ZONE,
  version bigint NOT NULL
);
CREATE INDEX idx_agent_eval_run_status ON agent_evaluation_runs (status);
CREATE INDEX idx_agent_eval_run_created ON agent_evaluation_runs (created_at);

CREATE TABLE agent_evaluation_cases (
  id varchar(36) PRIMARY KEY,
  run_id varchar(36) NOT NULL,
  case_key varchar(160) NOT NULL,
  input_hash varchar(64) NOT NULL,
  status varchar(20) NOT NULL
    CHECK (status IN ('PENDING', 'RUNNING', 'PAUSED', 'COMPLETED', 'FAILED', 'CANCELLED')),
  current_stage varchar(40) CHECK (current_stage IN (
    'RESUME_PARSE', 'JD_ANALYSIS', 'SKILL_SELECTION', 'QUESTION_GENERATION',
    'ANSWER_EVALUATION', 'REPORT_GENERATION', 'QUALITY_SCORING')),
  resume_id bigint,
  session_id varchar(36),
  error_summary varchar(500),
  created_at timestamp(6) WITH TIME ZONE NOT NULL,
  started_at timestamp(6) WITH TIME ZONE,
  updated_at timestamp(6) WITH TIME ZONE NOT NULL,
  completed_at timestamp(6) WITH TIME ZONE,
  version bigint NOT NULL,
  CONSTRAINT uk_agent_eval_case_run_key UNIQUE (run_id, case_key)
);
CREATE INDEX idx_agent_eval_case_status ON agent_evaluation_cases (status);
CREATE INDEX idx_agent_eval_case_run ON agent_evaluation_cases (run_id);

CREATE TABLE agent_evaluation_stages (
  id varchar(36) PRIMARY KEY,
  run_id varchar(36) NOT NULL,
  case_id varchar(36) NOT NULL,
  case_key varchar(160) NOT NULL,
  stage_type varchar(40) NOT NULL CHECK (stage_type IN (
    'RESUME_PARSE', 'JD_ANALYSIS', 'SKILL_SELECTION', 'QUESTION_GENERATION',
    'ANSWER_EVALUATION', 'REPORT_GENERATION', 'QUALITY_SCORING')),
  input_hash varchar(64) NOT NULL,
  prompt_version varchar(80) NOT NULL,
  provider varchar(64) NOT NULL,
  model varchar(120) NOT NULL,
  idempotency_key varchar(64) NOT NULL,
  status varchar(24) NOT NULL
    CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'RETRY_WAITING', 'PAUSED', 'FAILED', 'SKIPPED')),
  attempt_count integer NOT NULL,
  duration_ms bigint,
  prompt_tokens integer,
  completion_tokens integer,
  total_tokens integer,
  artifact_key varchar(500),
  error_type varchar(40) CHECK (error_type IN (
    'INVALID_CREDENTIAL', 'RATE_LIMITED', 'TRANSIENT_PROVIDER_ERROR', 'STRUCTURED_OUTPUT_ERROR',
    'INPUT_TOO_LARGE', 'CONTENT_FILTERED', 'INFRASTRUCTURE_ERROR', 'UNKNOWN')),
  error_summary varchar(500),
  created_at timestamp(6) WITH TIME ZONE NOT NULL,
  started_at timestamp(6) WITH TIME ZONE,
  updated_at timestamp(6) WITH TIME ZONE NOT NULL,
  completed_at timestamp(6) WITH TIME ZONE,
  next_retry_at timestamp(6) WITH TIME ZONE,
  version bigint NOT NULL,
  CONSTRAINT uk_agent_eval_stage_idempotency UNIQUE (idempotency_key)
);
CREATE INDEX idx_agent_eval_stage_status ON agent_evaluation_stages (status);
CREATE INDEX idx_agent_eval_stage_case ON agent_evaluation_stages (case_id);
CREATE INDEX idx_agent_eval_stage_created ON agent_evaluation_stages (created_at);

CREATE TABLE ai_call_audits (
  id varchar(36) PRIMARY KEY,
  run_id varchar(36) NOT NULL,
  case_id varchar(36) NOT NULL,
