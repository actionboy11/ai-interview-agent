-- Snapshot of the existing Hibernate schema. Legacy installations baseline at version 1.
-- Extensions may already be installed by docker/postgres/init.sql.
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS hstore WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA public;

CREATE TABLE resumes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_hash varchar(64) NOT NULL UNIQUE,
  original_filename varchar(255) NOT NULL,
  file_size bigint,
  content_type varchar(255),
  storage_key varchar(500),
  storage_url varchar(1000),
  resume_text text,
  uploaded_at timestamp(6) NOT NULL,
  last_accessed_at timestamp(6),
  access_count integer,
  analyze_status varchar(20) CHECK (analyze_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
  analyze_error varchar(500)
);

CREATE TABLE resume_analyses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_message_id varchar(36) UNIQUE,
  resume_id bigint NOT NULL REFERENCES resumes (id),
  overall_score integer,
  content_score integer,
  structure_score integer,
  skill_match_score integer,
  expression_score integer,
  project_score integer,
  summary text,
  strengths_json text,
  suggestions_json text,
  analyzed_at timestamp(6) NOT NULL
);

CREATE TABLE interview_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id varchar(36) NOT NULL UNIQUE,
  skill_id varchar(64),
  difficulty varchar(16),
  resume_id bigint REFERENCES resumes (id),
  total_questions integer,
  current_question_index integer,
  status varchar(20) CHECK (status IN ('CREATED', 'IN_PROGRESS', 'COMPLETED', 'EVALUATED')),
  questions_json text,
  overall_score integer,
  overall_feedback text,
  strengths_json text,
  improvements_json text,
  reference_answers_json text,
  created_at timestamp(6) NOT NULL,
  completed_at timestamp(6),
  evaluate_status varchar(20) CHECK (evaluate_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
  evaluate_error varchar(500),
  evaluation_message_id varchar(36) UNIQUE,
  llm_provider varchar(50)
);
CREATE INDEX idx_interview_session_resume_created ON interview_sessions (resume_id, created_at);
CREATE INDEX idx_interview_session_resume_status_created
  ON interview_sessions (resume_id, status, created_at);
CREATE INDEX idx_interview_session_skill_created ON interview_sessions (skill_id, created_at);

CREATE TABLE interview_answers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL REFERENCES interview_sessions (id),
  question_index integer,
  question text,
  category varchar(255),
  user_answer text,
  score integer,
  feedback text,
  reference_answer text,
  key_points_json text,
  answered_at timestamp(6) NOT NULL,
  CONSTRAINT uk_interview_answer_session_question UNIQUE (session_id, question_index)
);
CREATE INDEX idx_interview_answer_session_question ON interview_answers (session_id, question_index);

CREATE TABLE interview_schedule (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name varchar(255) NOT NULL,
  position varchar(255) NOT NULL,
  interview_time timestamp(6) NOT NULL,
  interview_type varchar(255),
  meeting_link text,
  round_number integer,
  interviewer varchar(255),
  notes text,
  status varchar(255) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED', 'RESCHEDULED')),
  created_at timestamp(6),
  updated_at timestamp(6)
);

CREATE TABLE knowledge_bases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_hash varchar(64) NOT NULL UNIQUE,
  name varchar(255) NOT NULL,
  category varchar(100),
  original_filename varchar(255) NOT NULL,
  file_size bigint,
  content_type varchar(255),
  storage_key varchar(500),
  storage_url varchar(1000),
  uploaded_at timestamp(6) NOT NULL,
  last_accessed_at timestamp(6),
  access_count integer,
  question_count integer,
  vector_status varchar(20) CHECK (vector_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
  vector_error varchar(500),
  chunk_count integer,
  vectorization_message_id varchar(36) UNIQUE
);
CREATE INDEX idx_kb_category ON knowledge_bases (category);

CREATE TABLE rag_chat_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(255) NOT NULL,
  status varchar(20) CHECK (status IN ('ACTIVE', 'ARCHIVED')),
  created_at timestamp(6) NOT NULL,
  updated_at timestamp(6),
  message_count integer,
  is_pinned boolean DEFAULT false
);
CREATE INDEX idx_rag_session_updated ON rag_chat_sessions (updated_at);

CREATE TABLE rag_chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL REFERENCES rag_chat_sessions (id),
  type varchar(20) NOT NULL CHECK (type IN ('USER', 'ASSISTANT')),
  content text NOT NULL,
  message_order integer NOT NULL,
  created_at timestamp(6) NOT NULL,
  updated_at timestamp(6),
  completed boolean
);
CREATE INDEX idx_rag_message_session ON rag_chat_messages (session_id);
CREATE INDEX idx_rag_message_order ON rag_chat_messages (session_id, message_order);

CREATE TABLE rag_session_knowledge_bases (
  session_id bigint NOT NULL REFERENCES rag_chat_sessions (id),
  knowledge_base_id bigint NOT NULL REFERENCES knowledge_bases (id),
  PRIMARY KEY (knowledge_base_id, session_id)
);

