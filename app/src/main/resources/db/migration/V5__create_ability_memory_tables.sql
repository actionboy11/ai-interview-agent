CREATE TABLE user_ability_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users (id),
  skill_id varchar(64) NOT NULL,
  category_key varchar(255) NOT NULL,
  level varchar(20) NOT NULL CHECK (level IN
    ('WEAK', 'DEVELOPING', 'COMPETENT', 'PROFICIENT', 'STRONG')),
  score integer NOT NULL,
  confidence float(53) NOT NULL,
  summary text,
  confirmed_evidence_count integer NOT NULL,
  status varchar(20) NOT NULL CHECK (status IN ('ACTIVE', 'DISABLED', 'NEEDS_REVIEW')),
  last_evaluated_at timestamp(6) WITH TIME ZONE,
  last_confirmed_at timestamp(6) WITH TIME ZONE,
  version bigint NOT NULL,
  CONSTRAINT uk_ability_profile_owner_skill_category UNIQUE (user_id, skill_id, category_key),
  CONSTRAINT ck_ability_profile_values CHECK
    (score between 0 and 100 and confidence between 0 and 1
      and confirmed_evidence_count >= 0)
);
CREATE INDEX idx_ability_profile_owner_skill_status
  ON user_ability_profiles (user_id, skill_id, status);

CREATE TABLE ability_profile_proposals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users (id),
  interview_session_id bigint NOT NULL REFERENCES interview_sessions (id),
  skill_id varchar(64) NOT NULL,
  category_key varchar(255) NOT NULL,
  previous_level varchar(20) CHECK (previous_level IN
    ('WEAK', 'DEVELOPING', 'COMPETENT', 'PROFICIENT', 'STRONG')),
  previous_score integer,
  proposed_level varchar(20) NOT NULL CHECK (proposed_level IN
    ('WEAK', 'DEVELOPING', 'COMPETENT', 'PROFICIENT', 'STRONG')),
  proposed_score integer NOT NULL,
  proposed_summary text,
  status varchar(20) NOT NULL CHECK (status IN
    ('PROPOSED', 'ACCEPTED', 'ACCEPTED_WITH_EDIT', 'REJECTED')),
  created_at timestamp(6) WITH TIME ZONE NOT NULL,
  decided_at timestamp(6) WITH TIME ZONE,
  version bigint NOT NULL,
  CONSTRAINT uk_ability_proposal_session_category UNIQUE
    (interview_session_id, category_key),
  CONSTRAINT ck_ability_proposal_scores CHECK
    ((previous_score is null or previous_score between 0 and 100)
      and proposed_score between 0 and 100)
);
CREATE INDEX idx_ability_proposal_owner_status
  ON ability_profile_proposals (user_id, status);
CREATE INDEX idx_ability_proposal_owner_session
  ON ability_profile_proposals (user_id, interview_session_id);

CREATE TABLE user_ability_evidence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users (id),
  interview_session_id bigint NOT NULL REFERENCES interview_sessions (id),
  interview_answer_id bigint NOT NULL REFERENCES interview_answers (id),
  proposal_id bigint NOT NULL REFERENCES ability_profile_proposals (id),
  skill_id varchar(64) NOT NULL,
  category_key varchar(255) NOT NULL,
  topic_summary text,
  question_score integer NOT NULL,
  difficulty varchar(16),
  feedback_summary text,
  occurred_at timestamp(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT uk_ability_evidence_answer UNIQUE (interview_answer_id),
  CONSTRAINT ck_ability_evidence_score CHECK (question_score between 0 and 100)
);
CREATE INDEX idx_ability_evidence_owner_skill
  ON user_ability_evidence (user_id, skill_id, category_key);
CREATE INDEX idx_ability_evidence_session ON user_ability_evidence (interview_session_id);
CREATE INDEX idx_ability_evidence_proposal ON user_ability_evidence (proposal_id);
