-- Execution mode is independent of the V1/V2 question planner.
ALTER TABLE interview_sessions ADD COLUMN execution_mode varchar(24)
  DEFAULT 'LEGACY_FIXED' NOT NULL
  CHECK (execution_mode IN ('LEGACY_FIXED', 'DYNAMIC_FOLLOW_UP'));

-- Legacy answers keep null submission metadata. Direct intents also have durable idempotency keys.
ALTER TABLE interview_answers ADD COLUMN submission_intent varchar(20)
  CHECK (submission_intent IN ('ANSWER', 'DONT_KNOW', 'SKIP'));
ALTER TABLE interview_answers ADD COLUMN request_id uuid;
ALTER TABLE interview_answers ADD COLUMN request_fingerprint varchar(64);
ALTER TABLE interview_answers ADD COLUMN submission_owner_id uuid;
ALTER TABLE interview_answers ADD CONSTRAINT uk_dynamic_answer_source
  UNIQUE (id, session_id, question_index, request_id);
ALTER TABLE interview_answers ADD CONSTRAINT uk_dynamic_answer_request
  UNIQUE (submission_owner_id, request_id);
ALTER TABLE interview_answers ADD CONSTRAINT fk_dynamic_answer_session_owner
  FOREIGN KEY (session_id, submission_owner_id)
  REFERENCES interview_sessions (id, owner_user_id);
ALTER TABLE interview_answers ADD CONSTRAINT ck_dynamic_answer_submission CHECK (
  (submission_intent is null and request_id is null and request_fingerprint is null
    and submission_owner_id is null) or (submission_intent is not null
    and request_id is not null and request_fingerprint is not null
    and submission_owner_id is not null));

CREATE TABLE interview_dynamic_runtime (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL,
  owner_user_id uuid NOT NULL,
  version bigint NOT NULL,
  execution_version integer NOT NULL,
  phase varchar(24) NOT NULL
    CHECK (phase IN ('WAITING_ANSWER', 'DECISION_PENDING', 'COMPLETED')),
  main_questions_json text NOT NULL,
  policy_json text NOT NULL,
  planned_main_question_count integer NOT NULL,
  max_follow_ups_per_group integer NOT NULL,
  total_follow_up_budget integer NOT NULL,
  decision_timeout_seconds integer NOT NULL,
  current_slot_id varchar(100) NOT NULL,
  current_main_ordinal integer NOT NULL,
  current_question_index integer NOT NULL,
  group_used_follow_ups integer NOT NULL,
  used_follow_ups integer NOT NULL,
  completed_main_count integer NOT NULL,
  group_end_reasons_json text NOT NULL,
  pending_decision_id uuid,
  frozen_version bigint,
  notice_code varchar(64),
  CONSTRAINT uk_dynamic_runtime_session UNIQUE (session_id),
  CONSTRAINT uk_dynamic_runtime_scope UNIQUE (session_id, owner_user_id),
  CONSTRAINT fk_dynamic_runtime_session FOREIGN KEY (session_id)
    REFERENCES interview_sessions (id) ON DELETE CASCADE,
  CONSTRAINT fk_dynamic_runtime_owner FOREIGN KEY (owner_user_id) REFERENCES users (id),
  CONSTRAINT fk_dynamic_runtime_session_owner FOREIGN KEY (session_id, owner_user_id)
    REFERENCES interview_sessions (id, owner_user_id) ON DELETE CASCADE,
  CONSTRAINT ck_dynamic_runtime_values CHECK (
    execution_version = 1 and planned_main_question_count > 0
    and max_follow_ups_per_group = 2
    and total_follow_up_budget = planned_main_question_count
    and decision_timeout_seconds > 0 and current_main_ordinal >= 0
    and current_main_ordinal < planned_main_question_count
    and current_question_index >= 0 and group_used_follow_ups between 0 and 2
    and used_follow_ups between 0 and total_follow_up_budget
    and group_used_follow_ups <= used_follow_ups
    and completed_main_count between 0 and planned_main_question_count
    and version >= 0 and (frozen_version is null or frozen_version >= 0))
);
CREATE INDEX idx_dynamic_runtime_phase ON interview_dynamic_runtime (phase);

CREATE TABLE interview_follow_up_decisions (
  id uuid PRIMARY KEY,
  session_id bigint NOT NULL,
  owner_user_id uuid NOT NULL,
  source_answer_id bigint NOT NULL,
  source_question_index integer NOT NULL,
  slot_id varchar(100) NOT NULL,
  request_id uuid NOT NULL,
  request_fingerprint varchar(64) NOT NULL,
  context_json text NOT NULL,
  deadline timestamp(6) WITH TIME ZONE NOT NULL,
  created_at timestamp(6) WITH TIME ZONE NOT NULL,
  expected_runtime_version bigint NOT NULL,
  status varchar(20) NOT NULL
    CHECK (status IN ('PENDING', 'PROCESSING', 'APPLIED', 'FAILED', 'CANCELLED')),
  delivery_status varchar(20) NOT NULL CHECK (delivery_status IN ('PENDING', 'PUBLISHED')),
  next_delivery_at timestamp(6) WITH TIME ZONE NOT NULL,
  delivery_attempts integer NOT NULL,
  published_at timestamp(6) WITH TIME ZONE,
  lease_until timestamp(6) WITH TIME ZONE,
  attempt_token uuid,
  model_action varchar(20) CHECK (model_action IN ('FOLLOW_UP', 'NEXT_MAIN')),
  model_reason varchar(24)
    CHECK (model_reason IN ('IMPORTANT_GAP', 'SUFFICIENT', 'NO_USEFUL_FOLLOW_UP', 'USER_DONT_KNOW')),
  reason_summary varchar(500),
  model_decision_json text,
  final_action varchar(20) CHECK (final_action IN ('FOLLOW_UP', 'NEXT_MAIN')),
  end_reason varchar(24) CHECK (end_reason IN
    ('SUFFICIENT', 'NO_USEFUL_FOLLOW_UP', 'DONT_KNOW', 'SKIP', 'BUDGET_EXHAUSTED',
      'SYSTEM_UNAVAILABLE', 'EARLY_COMPLETE')),
  error_code varchar(64),
  applied_runtime_version bigint,
  version bigint NOT NULL,
  CONSTRAINT uk_follow_up_source_answer UNIQUE (source_answer_id),
  CONSTRAINT uk_follow_up_owner_request UNIQUE (owner_user_id, request_id),
  CONSTRAINT fk_follow_up_session FOREIGN KEY (session_id)
    REFERENCES interview_sessions (id) ON DELETE CASCADE,
  CONSTRAINT fk_follow_up_owner FOREIGN KEY (owner_user_id) REFERENCES users (id),
  CONSTRAINT fk_follow_up_runtime_scope FOREIGN KEY (owner_user_id, session_id)
    REFERENCES interview_dynamic_runtime (owner_user_id, session_id) ON DELETE CASCADE,
  CONSTRAINT fk_follow_up_source_answer FOREIGN KEY (source_answer_id)
    REFERENCES interview_answers (id) ON DELETE CASCADE,
  CONSTRAINT fk_follow_up_answer_scope
    FOREIGN KEY (source_answer_id, source_question_index, request_id, session_id)
    REFERENCES interview_answers (id, question_index, request_id, session_id) ON DELETE CASCADE,
  CONSTRAINT ck_follow_up_values CHECK (
    source_question_index >= 0 and expected_runtime_version >= 0 and version >= 0
    and delivery_attempts >= 0 and deadline > created_at
    and (applied_runtime_version is null or applied_runtime_version >= 0))
);
CREATE INDEX idx_follow_up_delivery
  ON interview_follow_up_decisions (delivery_status, next_delivery_at);
CREATE INDEX idx_follow_up_recovery ON interview_follow_up_decisions (status, deadline);

CREATE TABLE interview_dynamic_evaluation_outbox (
  id uuid PRIMARY KEY,
  session_id bigint NOT NULL,
  owner_user_id uuid NOT NULL,
  frozen_version bigint NOT NULL,
  message_id uuid NOT NULL,
  frozen_snapshot_json text NOT NULL,
  delivery_status varchar(20) NOT NULL CHECK (delivery_status IN ('PENDING', 'PUBLISHED')),
  created_at timestamp(6) WITH TIME ZONE NOT NULL,
  next_delivery_at timestamp(6) WITH TIME ZONE NOT NULL,
  delivery_attempts integer NOT NULL,
  published_at timestamp(6) WITH TIME ZONE,
  lease_until timestamp(6) WITH TIME ZONE,
  attempt_token uuid,
  version bigint NOT NULL,
  CONSTRAINT uk_dynamic_evaluation_version UNIQUE (session_id, frozen_version),
  CONSTRAINT uk_dynamic_evaluation_message UNIQUE (message_id),
  CONSTRAINT fk_dynamic_evaluation_session FOREIGN KEY (session_id)
    REFERENCES interview_sessions (id) ON DELETE CASCADE,
  CONSTRAINT fk_dynamic_evaluation_owner FOREIGN KEY (owner_user_id) REFERENCES users (id),
  CONSTRAINT fk_dynamic_evaluation_runtime_scope FOREIGN KEY (owner_user_id, session_id)
    REFERENCES interview_dynamic_runtime (owner_user_id, session_id) ON DELETE CASCADE,
  CONSTRAINT ck_dynamic_evaluation_values CHECK (
    frozen_version >= 0 and delivery_attempts >= 0 and version >= 0)
);
CREATE INDEX idx_dynamic_evaluation_delivery
  ON interview_dynamic_evaluation_outbox (delivery_status, next_delivery_at);
