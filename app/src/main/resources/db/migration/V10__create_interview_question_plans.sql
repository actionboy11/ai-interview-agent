CREATE TABLE interview_question_plans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id bigint NOT NULL,
  owner_user_id uuid NOT NULL,
  plan_version integer NOT NULL,
  planning_mode varchar(20) NOT NULL CHECK (planning_mode IN ('ADAPTIVE', 'FIXED')),
  fallback_reason varchar(100),
  plan_json text NOT NULL,
  created_at timestamp(6) NOT NULL,
  CONSTRAINT fk_question_plan_session FOREIGN KEY (session_id) REFERENCES interview_sessions (id),
  CONSTRAINT fk_question_plan_owner FOREIGN KEY (owner_user_id) REFERENCES users (id),
  CONSTRAINT fk_question_plan_session_owner FOREIGN KEY (session_id, owner_user_id)
    REFERENCES interview_sessions (id, owner_user_id)
);
CREATE INDEX idx_question_plan_owner_session ON interview_question_plans (owner_user_id, session_id);
