ALTER TABLE user_ability_evidence ADD COLUMN slot_id varchar(100);
ALTER TABLE user_ability_evidence ADD CONSTRAINT uk_ability_evidence_scope
  UNIQUE (id, user_id, interview_session_id, category_key);

CREATE TABLE user_ability_evidence_sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evidence_id bigint NOT NULL,
  answer_id bigint NOT NULL,
  user_id uuid NOT NULL,
  interview_session_id bigint NOT NULL,
  category_key varchar(255) NOT NULL,
  CONSTRAINT uk_ability_evidence_source UNIQUE (evidence_id, answer_id),
  -- Match Hibernate's property order for composite non-primary-key associations.
  CONSTRAINT fk_ability_source_evidence_scope
    FOREIGN KEY (category_key, evidence_id, interview_session_id, user_id)
    REFERENCES user_ability_evidence (category_key, id, interview_session_id, user_id)
    ON DELETE CASCADE,
  CONSTRAINT fk_ability_source_answer_scope
    FOREIGN KEY (category_key, answer_id, interview_session_id)
    REFERENCES interview_answers (category_key, id, session_id),
  CONSTRAINT fk_ability_source_session_owner
    FOREIGN KEY (interview_session_id, user_id)
    REFERENCES interview_sessions (id, owner_user_id)
);
CREATE INDEX idx_ability_source_answer ON user_ability_evidence_sources (answer_id);
